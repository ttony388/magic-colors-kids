test('nearly colored picture animates automatically with its chosen colors',async({page})=>{
  await page.goto('/');await page.getByRole('button',{name:/Животни/}).click();await page.getByRole('button',{name:/Коте/}).click();
  await page.getByRole('button',{name:'Цвят 2',exact:true}).click();
  const regions=await page.locator('.svg-art [data-region]').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('data-region')!));
  const count=Math.ceil(regions.length*.8);
  for(const id of regions.slice(0,count-1))await page.locator(`[data-region="${id}"]`).dispatchEvent('pointerdown',{clientX:200,clientY:200,pointerType:'touch'});
  await expect(page.getByTestId('drawing-stage')).not.toHaveClass(/alive/);
  await page.locator(`[data-region="${regions[count-1]}"]`).dispatchEvent('pointerdown',{clientX:200,clientY:200,pointerType:'touch'});
  await expect(page.getByTestId('drawing-stage')).toHaveClass(/alive/);
  await expect(page.locator('.artwork-layer')).toHaveCSS('animation-name','picture-awake');
  await expect(page.locator(`[data-region="${regions[0]}"]`)).not.toHaveCSS('fill','rgb(255, 255, 255)');
  const chosen=await page.locator(`[data-region="${regions[0]}"]`).getAttribute('fill');
  expect(chosen).toBeTruthy();
  await expect.poll(async()=>page.evaluate(async()=>new Promise<boolean>((resolve)=>{const req=indexedDB.open('magic-colors',1);req.onsuccess=()=>{const read=req.result.transaction('drawings').objectStore('drawings').get('cat@v2:detailed');read.onsuccess=()=>resolve(read.result?.completed===true)}}))).toBe(true);
  await expect(page.getByTestId('drawing-stage')).not.toHaveClass(/alive/,{timeout:4500});
  await expect(page.locator(`[data-region="${regions[0]}"]`)).toHaveAttribute('fill',chosen!);
});
